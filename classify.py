def _clean(text: str) -> str:
    t = text or ""
    t = re.sub(r"#\S+", " ", t)                      # ハッシュタグ（#神戸グルメ など）は地域・ジャンル判定に使わない
    t = re.sub(r"hyogo_jiten|生きる兵庫事典|神戸線|神戸から", " ", t)  # 定型文・路線名・起点の表現
    t = re.sub(r"[A-Za-z0-9_.]{6,}", " ", t)        # @なしのアカウント名
    return t


def genre_of(text: str) -> str:
    t = _clean(text)
    head = t[:120]
    for name, pattern in PRIORITY_GENRES:
        if re.search(pattern, head, re.I):
            return name
    best = None
    for name, pattern in list(CONTENT_GENRES.items()) + PRIORITY_GENRES:
        m = re.search(pattern, t, re.I)
        if m and (best is None or m.start() < best[1]):
            best = (name, m.start())
    return best[0] if best else "その他"


def is_pr(text: str) -> bool:
    # 「PR・お仕事のご依頼はDMへ」のような連絡先の定型文は除く
    t = re.sub(r"PR\s?[･・/／&＆]\s?お仕事|PR\s?の?ご?依頼|お仕事の?ご?依頼", " ", text or "", flags=re.I)
    return bool(re.search(PR_PATTERN, t, re.I))


def region_of(text: str) -> str:
    """住所があればそれを採用。なければ地名の出現回数で一番多い市町。同数なら「兵庫県」、県外のみなら「県外」"""
    raw = text or ""
    addr = re.search(r"兵庫県(?:[^\s市町]{1,6}郡)?(\S{1,5}?[市町])", raw)
    if addr and addr.group(1) in MUNICIPALITIES:
        return addr.group(1)
    t = _clean(raw)
    count = Counter()
    for m in MUNICIPALITIES:
        count[m] += t.count(m) * 2
    aliases = sorted(((a, m) for m, al in AREA_ALIASES.items() for a in al), key=lambda x: -len(x[0]))
    rest = t
    for alias, muni in aliases:
        n = rest.count(alias)
        if n:
            count[muni] += n
            rest = rest.replace(alias, " ")
    count = +count
    # 「7選」「まとめ」など複数の場所を紹介する投稿は県全体扱い
    if len(count) >= 2 and re.search(r"\d+\s*選|まとめ|特集", t):
        return "兵庫県"
    if not count:
        return "県外" if re.search(OUTSIDE, t) else "兵庫県"
    top = count.most_common(2)
    if re.search(OUTSIDE, t) and not addr:
        outside_n = len(re.findall(OUTSIDE, t))
        if outside_n > top[0][1]:
            return "県外"
    if len(top) == 1 or top[0][1] > top[1][1]:
        return top[0][0]
    return "兵庫県"
